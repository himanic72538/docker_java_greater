public class Greater {
    public static void main(String[] args) {
        int a = 10;
        int b = 20;

        if (a > b) {
            System.out.println("a " + a + " is greater than b " + b);
        } else {
            System.out.println("b " + b + " is greater than a " + a);
        }
    }
}
